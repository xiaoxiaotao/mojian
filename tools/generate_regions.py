from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
regions=json.loads((root/'config/refresh_regions.json').read_text())
for x,y,w,h in regions:assert x%8==0 and w%8==0 and 0<=x<x+w<=800 and 0<=y<y+h<=480
text='// Generated by tools/generate_regions.py from config/refresh_regions.json\n#pragma once\nstruct ScreenRegion {int x,y,w,h;};\nstatic const ScreenRegion REFRESH_REGIONS[]={\n'+''.join(' {'+','.join(map(str,r))+'},\n' for r in regions)+'};\n'
(root/'firmware/src/refresh_regions.h').write_text(text)
