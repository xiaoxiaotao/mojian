#!/usr/bin/env python3
"""Generate identical offline preset catalogs. No user data, network or model calls."""
from pathlib import Path
import json,sys
ROOT=Path(__file__).resolve().parents[1]
rows=json.loads((ROOT/'config/desk-presets.json').read_text())
assert len(rows)==6 and len({r['id'] for r in rows})==6
for row in rows:
 assert set(row)=={'id','name','summary','requirements','template'}
 assert row['name']==row['template']['name'] and row['requirements']
 assert set(row['template'])=={'schema','name','settings'}
 assert set(row['template']['settings'])=={'layout','ratio','cardsVersion','card1','card2'}
 assert row['template']['schema']=='mojian-template-v1'
raw=json.dumps(rows,ensure_ascii=False,separators=(',',':'))
swift='''// Generated by tools/generate_preset_catalog.py; edit config/desk-presets.json.
import Foundation
struct DeskPreset:Identifiable {
 let id:String;let name:String;let summary:String;let requirements:[String];let template:[String:Any]
 static let all:[DeskPreset] = {
  let raw = #"""
'''+raw+'''
"""#
  guard let rows=try? JSONSerialization.jsonObject(with:Data(raw.utf8)) as? [[String:Any]] else{return []}
  return rows.compactMap { r in
   guard let id=r["id"] as? String,let name=r["name"] as? String,let summary=r["summary"] as? String,let requirements=r["requirements"] as? [String],let template=r["template"] as? [String:Any] else{return nil}
   return DeskPreset(id:id,name:name,summary:summary,requirements:requirements,template:template)
  }
 }()
}
'''
java='''// Generated by tools/generate_preset_catalog.py; edit config/desk-presets.json.
package com.desktodo.app;
import org.json.*;
final class PresetCatalog {
 static JSONArray all()throws JSONException{return new JSONArray('''+json.dumps(raw,ensure_ascii=False)+''');}
}
'''
for name,value in [('macos/Sources/PresetCatalog.swift',swift),('android/app/src/main/java/com/desktodo/app/PresetCatalog.java',java)]:
 path=ROOT/name
 if '--check' in sys.argv:
  assert path.read_text()==value,'Generated catalog out of date: '+name
 else:path.write_text(value)
print('PASS: six matching offline desktop presets')
